/**
 * Copies the storefront template stylesheets into the app, so the live
 * storefront (src/app/(storefront)) renders with exactly the CSS the static
 * templates were built and tested with.
 *
 *   src/styles/storefront/base.css    design/storefront-templates/_base/base.css, unchanged
 *   src/styles/storefront/themes.css  every storefront theme.css, scoped to
 *                                     <html data-template="<slug>"> so one bundle serves all three
 *
 * Theme rules are prefixed with :where([data-template="…"]), which adds no
 * specificity, so they override base.css by source order exactly as they do
 * when appended in the static build. :root becomes [data-template="…"] so the
 * theme's tokens beat the base tokens on the <html> element.
 *
 * Run after editing a template's CSS: npm run templates:css
 * Dependency-free on purpose, like design/storefront-templates/build.js.
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = join(root, "design", "storefront-templates");
const outDir = join(root, "src", "styles", "storefront");
const THEMES = ["linden-home", "sage-and-stem", "loftwood"];

const banner = (source) =>
  `/* GENERATED by scripts/build-storefront-css.mjs from ${source}. Do not edit; edit the template and re-run npm run templates:css. */\n`;

/** Splits on commas that aren't inside parentheses, e.g. `a, :is(b, c)` -> ["a", ":is(b, c)"]. */
function splitSelectors(selectorText) {
  const parts = [];
  let depth = 0;
  let current = "";
  for (const ch of selectorText) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      parts.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

function scopeSelector(selector, scope) {
  if (selector === ":root") return `[data-template="${scope}"]`;
  if (/^(html|body)\b/.test(selector)) return selector.replace(/^(html|body)/, `$1:where([data-template="${scope}"])`);
  return `:where([data-template="${scope}"]) ${selector}`;
}

/** Index of the brace that closes the block opened at `openIndex`. */
function matchingBrace(css, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < css.length; i++) {
    if (css[i] === "{") depth++;
    if (css[i] === "}" && --depth === 0) return i;
  }
  throw new Error("Unbalanced braces in CSS");
}

function scopeCss(css, scope) {
  let out = "";
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open === -1) {
      out += css.slice(i);
      break;
    }
    const prelude = css.slice(i, open).trim();
    const close = matchingBrace(css, open);
    const body = css.slice(open + 1, close);

    if (/^@(media|supports|container|layer)\b/.test(prelude)) {
      out += `${prelude} {\n${scopeCss(body, scope)}}\n`;
    } else if (prelude.startsWith("@")) {
      out += `${prelude} {${body}}\n`; // @font-face, @keyframes: leave untouched
    } else {
      out += `${splitSelectors(prelude).map((s) => scopeSelector(s, scope)).join(",\n")} {${body}}\n`;
    }
    i = close + 1;
  }
  return out;
}

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "");

mkdirSync(outDir, { recursive: true });

const base = readFileSync(join(templatesDir, "_base", "base.css"), "utf8");
writeFileSync(join(outDir, "base.css"), banner("design/storefront-templates/_base/base.css") + base);

const themes = THEMES.map((slug) => {
  const css = stripComments(readFileSync(join(templatesDir, slug, "theme.css"), "utf8")).trim();
  return `/* ---------- ${slug} ---------- */\n${css ? scopeCss(css, slug) : ""}`;
}).join("\n");
writeFileSync(join(outDir, "themes.css"), banner("design/storefront-templates/<slug>/theme.css") + themes);

mkdirSync(join(root, "public", "sf-assets"), { recursive: true });
copyFileSync(join(templatesDir, "_base", "icons.svg"), join(root, "public", "sf-assets", "icons.svg"));

console.log(`Storefront CSS written to ${outDir} (${THEMES.length} themes) and icons to public/sf-assets/icons.svg`);
